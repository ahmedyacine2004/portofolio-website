/**
 * Deeply retrieves a nested value from an object using dot notation
 * @param obj - The object to retrieve from
 * @param path - The dot notation path (e.g., "navigation.home")
 * @returns The value at the path or the path itself as fallback
 */
function getNestedValue(obj: Record<string, unknown> | unknown, path: string): unknown {
  const keys = path.split('.');
  let result: unknown = obj;

  for (let index = 0; index < keys.length; index += 1) {
    const remainingPath = keys.slice(index).join('.');
    if (result && typeof result === 'object' && remainingPath in result) {
      return (result as Record<string, unknown>)[remainingPath];
    }

    const key = keys[index];
    if (result && typeof result === 'object' && key in result) {
      result = (result as Record<string, unknown>)[key];
    } else {
      return path; // Return the key path as fallback
    }
  }

  return result;
}

/**
 * Custom hook for translations
 * @returns Object with `t` function and current `locale`
 */
export function useTranslation() {
  const locale = useLanguageStore((s) => s.locale);

  const t = (key: string, fallback?: string | { defaultValue?: string }): string => {
    const translationSet = translations[locale];
    const value = getNestedValue(translationSet, key);
    const defaultValue =
      typeof fallback === 'string'
        ? fallback
        : fallback && typeof fallback === 'object'
          ? fallback.defaultValue
          : undefined;

    // If value is the key path (fallback from getNestedValue), return fallback or key
    if (typeof value !== 'string' || value === key) {
      return defaultValue || fallback?.toString?.() || key;
    }

    return value;
  };

  const tArray = <T = unknown>(key: string): T[] => {
    const translationSet = translations[locale];
    const value = getNestedValue(translationSet, key);

    if (Array.isArray(value)) {
      return value as T[];
    }

    return [];
  };

  const tObject = <T = unknown>(key: string, fallback?: T): T => {
    const translationSet = translations[locale];
    const value = getNestedValue(translationSet, key);

    if (value && typeof value === 'object') {
      return value as T;
    }

    return fallback as T;
  };

  const projectText = (project: string, value: string): string =>
    t(`projects.${project}.content.${value}`, value);

  const skillPageText = (page: string, path: string, fallback?: string): string => {
    const translationSet = translations[locale];
    const value = getNestedValue(translationSet, `skillPages.${page}.${path}`);

    if (typeof value !== 'string' || value === `skillPages.${page}.${path}`) {
      return fallback || path;
    }

    return value;
  };

  return { t, tArray, tObject, projectText, skillPageText, locale };
}
